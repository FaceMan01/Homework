def play_cities():
    """
    Реализация локальной версии игры "Города" на одном компьютере.
    """

    cities_list = { 
        "москва", "санкт-петербург", "новосибирск", "екатеринбург", "нижний новгород",
        "казань", "челябинск", "омск", "самара", "ростов-на-дону",
        "уфа", "красноярск", "пермь", "воронеж", "волгоград",
        "краснодар", "саратов", "тюмень", "тольятти", "ижевск",
        "барнаул", "ульяновск", "владивосток", "ярославль", "хабаровск",
        "иркутск", "кемерово", "липецк", "пенза", "рязань",
        "томск", "астрахань", "курск", "орёл", "тверь",
        "тула", "чебоксары", "чита", "элиста", "якутск"
    }

    used_cities = set()  # Множество для отслеживания уже названных городов (необязательно в локальной версии, но полезно)
    last_letter = '' 
    current_player = 1

    print("Добро пожаловать в игру 'Города'!")
    print("Для выхода из игры введите '/q'.")

    while True:
        print(f"\nХод игрока {current_player}:")
        city = input("Введите город: ").strip().lower()  # Получаем ввод и приводим к нижнему регистру

        if city == "/q":
            print("Игра завершена.")
            break

        if not city.isalpha(): # Проверка, что введены только буквы
            print("Ошибка: В названии города должны быть только буквы.")
            continue

        if city not in cities_list:
            print("Ошибка: Такого города нет в списке или он уже был назван.")
            continue

        if last_letter and city[0] != last_letter:
            print(f"Ошибка: Город должен начинаться на букву '{last_letter.upper()}'")
            continue

        cities_list.remove(city) # Удаляем город из списка доступных, чтобы не повторялся
        used_cities.add(city) # Добавляем в список использованных (не обязательно в этой версии)

        # Находим последнюю букву для следующего хода (исключаем 'ь', 'ъ', 'ы')
        valid_last_letter = ''
        for char in reversed(city):
            if char not in ['ь', 'ъ', 'ы']:
                valid_last_letter = char
                break

        last_letter = valid_last_letter
        print(f"Принято! Следующий город должен начинаться на букву '{last_letter.upper()}'")

        current_player = 3 - current_player  # Переключаем игрока (1 <-> 2)

if __name__ == "__main__":
    play_cities()